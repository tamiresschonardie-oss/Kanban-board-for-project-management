type PriorityCandidateType = 'task' | 'project';
type PriorityScope = 'projects' | 'tasks';

const PRIORITY_SCOPE_STORAGE_KEY = 'crisdu_operational_priority_scope';

interface PriorityCandidate {
  id: string;
  entityId: string;
  itemType: PriorityCandidateType;
  title: string;
  assigneeId: string;
  assigneeName: string;
  workspace: string;
  projectId?: string;
  projectName?: string;
  operationalStatus: 'active' | 'paused' | 'completed' | 'cancelled';
  statusLabel: string;
  badge: string;
  secondary: string;
}

interface PriorityDragItem {
  candidateId: string;
  sourceList: 'prioritized' | 'backlog';
}

interface PriorityCycleDraft {
  editingId: string | null;
  name: string;
  description: string;
  type: PriorityCycleType;
  startDate: string;
  endDate: string;
  durationDays: string;
  active: boolean;
  nameAutoGenerated: boolean;
}

function buildCandidateId(itemType: PriorityCandidateType, entityId: string) {
  return `${itemType}:${entityId}`;
}

function createInitialCycleDraft(): PriorityCycleDraft {
  const now = new Date();
  const startDate = now.toISOString().slice(0, 10);
  const durationDays = String(getPriorityCycleDefaultDuration('week') || 7);
  const endDate = calculatePriorityCycleEndDate(startDate, Number(durationDays));

  return {
    editingId: null,
    name: getPriorityCycleSuggestedName({ type: 'week', startDate }),
    description: '',
    type: 'week',
    startDate,
    endDate,
    durationDays,
    active: true,
    nameAutoGenerated: true,
  };
}

